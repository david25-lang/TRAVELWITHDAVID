const normalizeQuery = (query) =>
  query
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, ',')
    .replace(/,+/g, ',')
    .replace(/^,|,$/g, '');

const hashSeed = (value) => {
  const source = String(value);
  let hash = 0;

  for (let index = 0; index < source.length; index += 1) {
    hash = (hash * 31 + source.charCodeAt(index)) >>> 0;
  }

  return hash;
};

export const imageUrl = (seed, width = 1200, height = 900) => {
  const hash = hashSeed(seed);
  const query = photoQueries[seed] || 'premium travel destination';
  const slug = normalizeQuery(query);
  return `https://loremflickr.com/${width}/${height}/${slug}?lock=${hash}`;
};

